import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { parseOwnerId, isOwner, displayRole, canChangeRole, type RoleSubject } from "../src/server/account-state/owner-policy";
import { parseAuditQuery } from "../src/server/account-state/admin-query";
const owner: RoleSubject = { userId: "existing-admin", role: "ADMIN", status: "ACTIVE" };
const admin: RoleSubject = { userId: "other-admin", role: "ADMIN", status: "ACTIVE" };
const member: RoleSubject = { userId: "member", role: "MEMBER", status: "ACTIVE" };
for (const invalid of [undefined, "", " a", "../a", "a".repeat(256)]) assert.equal(parseOwnerId(invalid), null);
assert.equal(parseOwnerId(owner.userId), owner.userId);
assert.equal(displayRole(owner.userId, owner), "OWNER");
assert.equal(displayRole(owner.userId, admin), "ADMIN");
assert.equal(isOwner(null, owner), false);
assert.equal(isOwner(owner.userId, { ...owner, role: "MEMBER" }), false);
assert.equal(isOwner(owner.userId, { ...owner, status: "SUSPENDED" }), false);
assert.equal(canChangeRole(owner.userId, owner, member, "PROMOTE"), true);
assert.equal(canChangeRole(owner.userId, owner, admin, "DEMOTE"), true);
for (const actor of [admin, member, { ...owner, status: "SUSPENDED" }]) assert.equal(canChangeRole(owner.userId, actor, member, "PROMOTE"), false);
for (const status of ["PENDING_APPROVAL", "UNVERIFIED", "SUSPENDED", "REJECTED"]) assert.equal(canChangeRole(owner.userId, owner, { ...member, status }, "PROMOTE"), false);
assert.equal(canChangeRole(owner.userId, owner, owner, "DEMOTE"), false);
assert.equal(canChangeRole(null, owner, member, "PROMOTE"), false);
assert.equal(canChangeRole(owner.userId, owner, admin, "PROMOTE"), false);
assert.equal(canChangeRole(owner.userId, owner, member, "DEMOTE"), false);
assert.equal(parseAuditQuery({ action: "ADMIN_ROLE_GRANTED" }).action, "ADMIN_ROLE_GRANTED");
assert.equal(parseAuditQuery({ action: "ADMIN_ROLE_REVOKED" }).action, "ADMIN_ROLE_REVOKED");
// Structural regression checks; not a substitute for live SQL/HTTP tests.
const source = readFileSync("src/server/account-state/owner-admin.ts", "utf8");
for (const required of ["await requireAdmin()", "await checkRateLimit(\"ownerRole\"", "await auth.api.verifyPassword", "verified.status !== true", "FOR UPDATE", "DELETE FROM \"session\"", "INSERT INTO \"audit_logs\"", "target.\"user_id\" <> ", "target.\"status\" = 'ACTIVE'"]) assert.ok(source.includes(required), required);
assert.ok(source.indexOf("await checkRateLimit") < source.indexOf("await auth.api.verifyPassword"));
assert.ok(source.indexOf("await auth.api.verifyPassword") < source.indexOf("WITH transitioned"));
assert.match(readFileSync("src/server/account-state/admin.ts", "utf8"), /IS DISTINCT FROM/);
console.log("PHASE 18 OWNER POLICY AND STRUCTURAL TESTS: PASS");
